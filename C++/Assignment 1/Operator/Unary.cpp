#include <iostream>
using namespace std;

int main() {
	int a = 45;

	cout << "Initial value of a: " << a << endl;

	// Unary plus
	cout << "Unary +a = " << +a << endl;

	// Unary minus
	cout << "Unary -a = " << -a << endl;

	// Increment operator
	cout << "Pre-increment (++a) = " << ++a << endl;

	// Decrement operator
	cout << "Pre-decrement (--a) = " << --a << endl;

	// Logical NOT
	cout << "Logical NOT (!a) = " << !a << endl;

	return 0;
}